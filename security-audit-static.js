#!/usr/bin/env node
'use strict';
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const html=read('index.html'), app=read('app.js'), boot=read('security-bootstrap.js'), trc=read('transpetro-cyber-data.js'), dpv=read('dataprev-visuals.js');
const runtime=[html,app,boot,trc,read('dataprev-history-data.js'),read('adaptive-engine.js'),read('flashcards-engine.js'),dpv].join('\n');
let checks=0; const failures=[]; const assert=(c,l)=>{checks++;if(!c)failures.push(l)};
assert(/Content-Security-Policy/i.test(html),'CSP definida');
for(const d of ["default-src 'self'","script-src 'self'","connect-src 'none'","frame-src 'none'","object-src 'none'","base-uri 'none'","form-action 'none'"]) assert(html.includes(d),`CSP ${d}`);
assert(/<meta name="referrer" content="no-referrer">/i.test(html),'Referrer no-referrer');
assert(html.includes("img-src 'self' data: https://i.ytimg.com"),'Somente host autorizado de thumbnail');
assert(!/<script(?![^>]*\bsrc=)[^>]*>[\s\S]*?<\/script>/i.test(html),'Sem JS inline');
assert(!/<iframe\b/i.test(runtime),'Sem iframe');
assert(!/\blocalStorage\.clear\s*\(/.test(runtime),'Sem localStorage.clear');
assert(!/\beval\s*\(|\bnew\s+Function\s*\(|document\.write\s*\(/.test(runtime),'Sem execução dinâmica perigosa');
assert(/safeExternalUrl/.test(app)&&/safeAssetPath/.test(app),'Sanitização de URL/caminho presente');
assert(/clearVersa/.test(app),'Limpeza limitada às chaves Versa');
assert(html.includes('transpetro-cyber-data.js'),'Trilha TRANSPETRO carregada explicitamente');
assert(html.indexOf('transpetro-cyber-data.js')<html.indexOf('flashcards-priority-data.js'),'Ordem segura de carregamento TRANSPETRO');
assert(html.includes('dataprev-visuals.js'),'Catálogo visual DATAPREV carregado explicitamente');
assert(html.indexOf('dataprev-visuals.js')<html.indexOf('app.js'),'Visuais DATAPREV carregam antes do app');
const blanks=app.match(/<a\b[^>]*target=["']_blank["'][^>]*>/gi)||[];
assert(blanks.length>0,'Links externos encontrados');
assert(blanks.every(t=>/rel=["'][^"']*noopener[^"']*noreferrer[^"']*["']/i.test(t)),'noopener/noreferrer em target blank');
assert(blanks.every(t=>/referrerpolicy=["']no-referrer["']/i.test(t)),'no-referrer em links externos');
assert(!/(?:api[_-]?key|client[_-]?secret|access[_-]?token|private[_-]?key|password)\s*[:=]\s*["'][^"']{8,}["']/i.test(runtime),'Sem segredo aparente');
const payload={status:failures.length?'failed':'passed',auditedAt:'2026-08-13',checks,failures,scope:'static'};
fs.writeFileSync(path.join(root,'AUDITORIA_SEGURANCA_ESTATICA_V1.8.1.json'),JSON.stringify(payload,null,2)+'\n');
console.log(JSON.stringify(payload,null,2));if(failures.length)process.exit(1);
